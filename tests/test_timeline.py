"""Fixture-based tests for the voyage timeline endpoint (no network).

Validates the golden fixture at frontend/e2e/fixtures/golden-voyage-timeline.json:
top-level keys, not_available, per-variable provenance, sun position, size cap and
monotonic UTC times.
"""
from __future__ import annotations

import json
import math
from datetime import datetime
from pathlib import Path

import pytest

REPO = Path(__file__).resolve().parents[1]
FIXTURE = REPO / "frontend" / "e2e" / "fixtures" / "golden-voyage-timeline.json"
MAX_BYTES = 5 * 1024 * 1024

STEP_KEYS = {
    "t_utc", "lat", "lon", "sog_kn", "cog", "heading", "ice_conc",
    "wind_u", "wind_v", "hs", "tp", "wave_dir", "current_u", "current_v",
    "nearby_bergs", "alerts", "sun_azimuth_deg", "sun_elevation_deg",
    "provenance_by_variable",
}
PROV_KEYS = {"kind", "source", "product", "valid_time", "age_hours"}


def _load_fixture():
    assert FIXTURE.is_file(), "golden fixture must be generated by scripts/export_golden_timeline.py"
    return json.loads(FIXTURE.read_text())


def test_fixture_exists_and_under_size_cap():
    size = FIXTURE.stat().st_size
    assert size <= MAX_BYTES, f"fixture {size} bytes exceeds 5 MB cap"


def test_top_level_keys():
    d = _load_fixture()
    assert set(d.keys()) == {"voyage_id", "step_min", "n_steps", "not_available", "steps"}
    assert isinstance(d["step_min"], (int, float)) and d["step_min"] > 0
    assert isinstance(d["n_steps"], int) and d["n_steps"] == len(d["steps"])
    assert isinstance(d["not_available"], list)


def test_steps_monotonic_utc():
    d = _load_fixture()
    times = [s["t_utc"] for s in d["steps"]]
    parsed = [datetime.fromisoformat(t.replace("Z", "+00:00")) for t in times]
    assert parsed == sorted(parsed), "t_utc must be monotonic"
    assert len(parsed) > 1


def test_each_step_has_required_keys():
    d = _load_fixture()
    for s in d["steps"]:
        assert set(s.keys()) == STEP_KEYS, set(s.keys()) ^ STEP_KEYS
        assert -90 <= s["lat"] <= 90
        assert -180 <= s["lon"] <= 180
        assert s["sog_kn"] >= 0


def test_provenance_on_every_variable():
    d = _load_fixture()
    for s in d["steps"]:
        prov = s["provenance_by_variable"]
        assert isinstance(prov, dict)
        for var, entry in prov.items():
            assert set(entry.keys()) == PROV_KEYS, (var, entry)
            assert entry["kind"] in {"observed", "real_forecast", "simulated", "synthetic",
                                     "experimental_ml", "real-seed"}
            assert isinstance(entry["source"], str) and entry["source"]


def test_ice_conc_provenance_is_observed_in_replay():
    d = _load_fixture()
    provs = [s["provenance_by_variable"].get("ice_conc") for s in d["steps"] if s.get("ice_conc") is not None]
    # The golden voyage is replay against NSIDC V6, so ice_conc must be observed.
    assert any(p and p["kind"] == "observed" for p in provs), provs


def test_sun_position_ranges():
    d = _load_fixture()
    for s in d["steps"]:
        az, el = s["sun_azimuth_deg"], s["sun_elevation_deg"]
        if az is not None:
            assert 0.0 <= az < 360.0
        if el is not None:
            assert -90.0 <= el <= 90.0


def test_not_available_lists_only_known_keys():
    d = _load_fixture()
    known = STEP_KEYS | {"environment_sample", "bergs", "sun"}
    for name in d["not_available"]:
        assert name in known, name
